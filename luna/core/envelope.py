"""Служебные пометки в реплике человека — в подписанном конверте.

Ниблер, почта команды и фоновые команды доходят до модели внутри
сообщения user. Раньше это были строки «[Ниблер: …]» прямо перед словами
человека, и мелкие модели принимали их за просьбы человека. Теперь
пометки — в отдельном блоке с подписью «не человек», слова человека —
в своём. Одна функция на агента и на сборку истории из журнала, чтобы
продолжённая сессия видела то же, что видела живая.
"""

from __future__ import annotations

# Кто может оставить пометку; подпись — как её увидит модель.
SOURCES = {
    "nibbler": "Ниблер — твой наблюдатель, не человек",
    "mail": "Почта команды — письмо спутника",
    "bg": "Фоновая команда",
}

OPEN = "<пометки_харнесса>"
CLOSE = "</пометки_харнесса>"
HUMAN_OPEN = "<человек>"
HUMAN_CLOSE = "</человек>"

# Строка для системного промпта: как читать конверт.
PROMPT_HINT = (
    "Если в сообщении есть блок " + OPEN + ", это служебные пометки харнесса "
    "(Ниблер, почта команды, фон), их писал не человек. Слова человека — "
    "только в блоке " + HUMAN_OPEN + " или, если блоков нет, всё сообщение. "
    "Пометки учитывай, но не отвечай на них как на просьбы человека."
)


def compose(text: str, notes) -> str:
    """Реплика с пометками. notes — [{"from": источник, "text": …}]."""
    notes = [n for n in (notes or []) if str(n.get("text") or "").strip()]
    if not notes:
        return text
    lines = [OPEN]
    for note in notes:
        src = str(note.get("from") or "")
        label = SOURCES.get(src, src or "харнесс")
        lines.append("- " + label + ": " + str(note["text"]).strip())
    lines.append(CLOSE)
    if text:
        lines += ["", HUMAN_OPEN, text, HUMAN_CLOSE]
    return "\n".join(lines)
