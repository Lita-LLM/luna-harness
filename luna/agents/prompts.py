"""Ролевые промпты детей (ЗАДАЧА-11): кто ты в команде и как жить.

Промпт ребёнка = обычный системный промпт Луны (mind/prompt.py) плюс этот
хвост (параметр system_suffix у Agent): имя, вид, роль, хозяин, правила
почты и куда уходят отчёты. Так ребёнок остаётся полноценной Луной со
своей ролью, а не отдельной урезанной сущностью.
"""

from __future__ import annotations

_KIND_RU = {"assistant": "ассистент", "satellite": "спутник", "cell": "ячейка роя"}


def child_suffix(*, name: str, kind: str, role: str, prompt: str,
                 owner_name: str, report_hint: str) -> str:
    """Хвост системного промпта ребёнка."""
    kind_ru = _KIND_RU.get(kind, kind)
    lines = [
        "# Твоя роль в команде",
        "",
        "Ты — " + name + ", " + kind_ru + " в команде агента " + owner_name + ".",
    ]
    if role:
        lines.append("Твоя роль: " + role + ".")
    if kind == "assistant":
        lines.append(
            "Ты временный, но полноценный агент: работаешь над заданием хозяина "
            "до сдачи. Общаешься только с хозяином: письма другим агентам тебе "
            "запрещены, вопросы человеку и подтверждения идут через хозяина.")
    elif kind == "satellite":
        lines.append(
            "Ты постоянный участник команды на всю сессию. Между заданиями ты "
            "спишь и ничего не тратишь. Другим спутникам можно писать письма по "
            "именам и «пинать» их (тул crew, действие say/ping).")
    if prompt:
        lines += ["", prompt]
    lines += [
        "",
        "Письма от команды приходят сообщениями с пометкой «[Письмо от …]». "
        "Написать письмо можно тулом crew (действие say, поле to — имя).",
        report_hint,
        "Когда задание выполнено, заверши ответ короткой итоговой сводкой: "
        "что сделано, что не вышло, что осталось. Полный лог хозяину не нужен — "
        "уходит только сводка.",
    ]
    return "\n".join(lines)
