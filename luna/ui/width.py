_ZERO_CATEGORIES = frozenset({"Mn", "Me", "Cf", "Cc"})


def _in_ranges(code: int, ranges) -> bool:
    for lo, hi in ranges:
        if lo <= code <= hi:
            return True
    return False


def char_width(ch: str) -> int:
    """Ширина одного символа: 0, 1 или 2 ячейки."""
    if not ch:
        return 0
    code = ord(ch)
    if unicodedata.combining(ch) or unicodedata.category(ch) in _ZERO_CATEGORIES:
        return 0
    known = _KNOWN_WIDTHS.get(ch)
    if known is not None:
        return known
    if unicodedata.east_asian_width(ch) in ("W", "F"):
        return 2
    if _in_ranges(code, _EMOJI_RANGES) or _in_ranges(code, _EMOJI_PRESENTATION):
        return 2
    return 1


def str_width(text: str) -> int:
    """Ширина строки в ячейках (без управляющих последовательностей)."""
    return sum(char_width(ch) for ch in text)


def fits(text: str, width: int) -> str:
    """Обрезать строку до ширины, не разрезая широкий символ пополам."""
    out = []
    used = 0
    for ch in text:
        w = char_width(ch)
        if used + w > width:
            break
        out.append(ch)
        used += w
    return "".join(out)
