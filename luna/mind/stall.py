"""Ход кончился без вызова тула, хотя модель явно собиралась действовать.

Некоторые модели (часто бесплатные с роутеров) пишут «сейчас прочитаю
файл» и замолкают: думают, что их позовут снова и тогда они вызовут тул.
Другие пишут вызов текстом в формате, которого Луна не знает. Третьи
отдают пустой ответ. Во всех трёх случаях ход просто кончался, и человек
видел обещание без дела.

Тут — грубая, но дешёвая диагностика последнего ответа и текст подсказки,
которую харнесс отправит модели. Ложное срабатывание стоит одного лишнего
шага модели, поэтому подсказка разрешает и честно ответить «готово».
"""

from __future__ import annotations

import re

# Глаголы первого лица будущего времени: «прочитаю», «проверим».
_RU_VERBS = (
    "прочитаю|прочту|почитаю|посмотрю|гляну|загляну|проверю|перепроверю|запущу|открою|"
    "изучу|найду|поищу|создам|исправлю|поправлю|подправлю|починю|выполню|вызову|сделаю|"
    "напишу|допишу|перепишу|попробую|обновлю|добавлю|удалю|уберу|соберу|протестирую|"
    "прогоню|исследую|начну|приступлю|займусь|разберусь|применю|внесу|изменю|почищу|"
    "скачаю|установлю|запишу|сохраню|переименую|перенесу|сравню|проанализирую|просмотрю|"
    "сгенерирую|отредактирую|вставлю|заменю|скопирую|выясню|уточню|посчитаю|"
    "прочитаем|посмотрим|проверим|запустим|откроем|изучим|найд[её]м|поищем|создадим|"
    "исправим|сделаем|попробуем|начн[её]м|займ[её]мся|разбер[её]мся|глянем|заглянем"
)
_RU = re.compile(r"(?<![а-яё])(?:" + _RU_VERBS + r")(?![а-яё])|(?<![а-яё])буду\s+\w+",
                 re.I)
_EN = re.compile(r"\b(?:let me|let's|i'll|i will|i'm going to|i am going to|"
                 r"now i|next,? i|i need to|first,? i)\b", re.I)
# Предложение человеку, а не обещание себе: «если хочешь, проверю».
_OFFER = re.compile(r"\?|если (?:хочешь|хотите|нужно|надо|скажешь|скажете|понадобится)|"
                    r"\bмогу\b|\bхочешь\b|would you|if you|let me know|shall i|"
                    r"want me|do you want", re.I)
# Следы попытки вызвать тул текстом.
_MARKUP = re.compile(r"<tool_call|</?function[=\s>]|<invoke\b|\[TOOL_CALLS\]|<\|tool|"
                     r"<｜tool|tool_call_begin|to=functions\.|\"tool_calls\"\s*:|"
                     r"\"arguments\"\s*:|```tool_code|<\|python_tag\|>|Action Input:")

_TAIL = 500  # судим по концу ответа: обещание в середине могло быть исполнено


def _tail(text: str) -> str:
    text = (text or "").strip()
    cut = text.rfind("\n\n", 0, max(0, len(text) - 40))
    tail = text[cut + 2:] if cut != -1 else text
    return tail[-_TAIL:]


def diagnose(text: str, names=()) -> str:
    """'' — ответ как ответ; 'broken' — вызов текстом, не распознан;
    'promise' — пообещала действие и закончила; 'empty' — ни слова."""
    body = (text or "").strip()
    if not body:
        return "empty"
    tail = _tail(body)
    if _MARKUP.search(tail) or _named_call(tail, names):
        return "broken"
    if _OFFER.search(tail):
        return ""
    if _RU.search(tail) or _EN.search(tail):
        return "promise"
    return ""


def _named_call(tail: str, names) -> bool:
    """read(path=…) или bash {…} — имя тула вплотную к аргументам."""
    names = [n for n in names or () if n]
    if not names:
        return False
    alt = "|".join(re.escape(n) for n in sorted(names, key=len, reverse=True))
    return re.search(r"(?<![\w.])(?:" + alt + r")\s*(?:\(\s*\w+\s*=|:?\s*\{\s*\")", tail) \
        is not None


